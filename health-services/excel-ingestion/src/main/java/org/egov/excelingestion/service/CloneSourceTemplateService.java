package org.egov.excelingestion.service;

import lombok.extern.slf4j.Slf4j;
import org.apache.poi.ss.usermodel.Workbook;
import org.apache.poi.xssf.usermodel.XSSFWorkbook;
import org.egov.common.contract.request.RequestInfo;
import org.egov.excelingestion.config.ExcelIngestionConfig;
import org.egov.excelingestion.config.ProcessingConstants;
import org.egov.excelingestion.web.models.CampaignSearchResponse;
import org.egov.excelingestion.web.models.GenerateResource;
import org.springframework.stereotype.Service;

import java.io.ByteArrayInputStream;
import java.io.ByteArrayOutputStream;
import java.util.List;
import java.util.Map;
import java.util.Objects;
import java.util.Set;
import java.util.stream.Collectors;

/**
 * A template keeps the data the campaign already had. A clone that agrees with its source on Outside Household (both use
 * it, or neither does) gets the source's filled file itself. When a campaign adds or drops Outside Household after a file
 * was uploaded, or a clone adds or drops it compared with its source, the template is generated as for any campaign (so
 * the Outside Household sheet appears with the area's sites, or not at all) and the earlier file's users, targets and
 * facilities are copied into it. The clone rules apply only to a clone on its source's area, of a campaign type listed in
 * excel.ingestion.outside.household.campaign.types (POLIO by default); other clones get their template as before.
 */
@Service
@Slf4j
public class CloneSourceTemplateService {

    static final String UNIFIED_CONSOLE_RESOURCE_TYPE = "unified-console-resources";
    private static final String OWN_FILE = "its file before Outside Household changed";
    private static final int MAX_EARLIER_FILES = 5;

    private final CampaignService campaignService;
    private final FileStoreService fileStoreService;
    private final ExcelIngestionConfig config;

    public CloneSourceTemplateService(CampaignService campaignService, FileStoreService fileStoreService, ExcelIngestionConfig config) {
        this.campaignService = campaignService;
        this.fileStoreService = fileStoreService;
        this.config = config;
    }

    /** A clone on its source's area whose source has a filled file. */
    private record CloneOfSource(String sourceId, String sourceFileStoreId, boolean sameOutsideHouseholdChoice) {
    }

    /** The source's file id to use as this generation's template, or null to generate the template as usual. */
    public String sourceFileForUnchangedClone(GenerateResource resource, RequestInfo requestInfo) {
        try {
            CloneOfSource clone = cloneOfSource(resource, requestInfo);
            if (clone == null || !clone.sameOutsideHouseholdChoice()) {
                return null;
            }
            log.info("Clone {} agrees with its source {} on Outside Household: template = source file {}",
                    resource.getReferenceId(), clone.sourceId(), clone.sourceFileStoreId());
            return clone.sourceFileStoreId();
        } catch (Exception e) {
            log.warn("Could not compare clone {} with its source; generating the template as usual: {}",
                    resource.getReferenceId(), e.getMessage());
            return null;
        }
    }

    /**
     * The generated template with the rows of an earlier file copied into it: the campaign's own file from before a save
     * that added or dropped Outside Household, or else, for a clone that adds or drops it, its source's file. When the
     * campaign's template has the Outside Household sheet again, its site rows come from the most recent of the campaign's
     * earlier files that has any (a file uploaded without the sheet in between is passed over). Any other generation, or
     * any failure, returns the generated bytes unchanged.
     */
    public byte[] withSourceData(GenerateResource resource, RequestInfo requestInfo, byte[] generated) {
        if (generated == null) {
            return null;
        }
        try {
            String fileStoreId = previousFile(resource);
            String from = OWN_FILE;
            if (fileStoreId == null) {
                CloneOfSource clone = cloneOfSource(resource, requestInfo);
                if (clone == null || clone.sameOutsideHouseholdChoice()) {
                    return generated;
                }
                fileStoreId = clone.sourceFileStoreId();
                from = "its source " + clone.sourceId();
            }
            try (Workbook source = fileStoreService.downloadExcelFromFileStore(fileStoreId, resource.getTenantId());
                 XSSFWorkbook template = new XSSFWorkbook(new ByteArrayInputStream(generated))) {
                int rows = CloneSourceDataMerger.copyRows(source, template);
                if (from.equals(OWN_FILE)) {
                    rows += copyOutsideHouseholdRows(resource, fileStoreId, source, template);
                }
                ByteArrayOutputStream out = new ByteArrayOutputStream(generated.length + 64 * 1024);
                template.write(out);
                log.info("Campaign {}: copied {} rows of {} (file {}) into the new template", resource.getReferenceId(), rows, from, fileStoreId);
                return out.toByteArray();
            }
        } catch (Exception e) {
            log.warn("Could not copy an earlier file's rows into campaign {}'s template; keeping the generated template: {}",
                    resource.getReferenceId(), e.getMessage());
            return generated;
        }
    }

    /**
     * Site rows for a template that has the Outside Household sheet: from the first of the campaign's file before the change
     * and its earlier files (newest first, as project-factory sends them) whose Outside Household sheet has a site row.
     */
    private int copyOutsideHouseholdRows(GenerateResource resource, String previousFile, Workbook previous, XSSFWorkbook template) {
        if (!CloneSourceDataMerger.hasOutsideHouseholdSheet(template)) {
            return 0;
        }
        if (CloneSourceDataMerger.hasOutsideHouseholdRows(previous)) {
            return CloneSourceDataMerger.copyOutsideHouseholdRows(previous, template);
        }
        for (String earlier : earlierFiles(resource)) {
            if (earlier.equals(previousFile)) {
                continue;
            }
            try (Workbook workbook = fileStoreService.downloadExcelFromFileStore(earlier, resource.getTenantId())) {
                if (CloneSourceDataMerger.hasOutsideHouseholdRows(workbook)) {
                    int rows = CloneSourceDataMerger.copyOutsideHouseholdRows(workbook, template);
                    log.info("Campaign {}: copied {} Outside Household rows of its earlier file {}", resource.getReferenceId(), rows, earlier);
                    return rows;
                }
            } catch (Exception e) {
                log.warn("Campaign {}: could not read earlier file {} for its Outside Household rows: {}", resource.getReferenceId(), earlier, e.getMessage());
            }
        }
        return 0;
    }

    /** The campaign's earlier files, newest first, as project-factory sends them; empty when none are sent. */
    private static List<String> earlierFiles(GenerateResource resource) {
        Object ids = resource.getAdditionalDetails() == null ? null
                : resource.getAdditionalDetails().get(ProcessingConstants.GENERATE_DETAIL_EARLIER_FILES_KEY);
        if (!(ids instanceof List)) {
            return List.of();
        }
        return ((List<?>) ids).stream().filter(String.class::isInstance).map(id -> trimToNull((String) id))
                .filter(Objects::nonNull).distinct().limit(MAX_EARLIER_FILES).toList();
    }

    /** The campaign's file from before a save that added or dropped Outside Household, as project-factory sends it. */
    private static String previousFile(GenerateResource resource) {
        if (resource == null || !ProcessingConstants.UNIFIED_CONSOLE_TYPE.equals(resource.getType())
                || ProcessingConstants.REFERENCE_TYPE_ATTENDANCE_REGISTER.equals(resource.getReferenceType())
                || resource.getAdditionalDetails() == null) {
            return null;
        }
        Object id = resource.getAdditionalDetails().get(ProcessingConstants.GENERATE_DETAIL_PREVIOUS_FILE_KEY);
        return id instanceof String ? trimToNull((String) id) : null;
    }

    private CloneOfSource cloneOfSource(GenerateResource resource, RequestInfo requestInfo) {
        if (!config.isCloneReuseSourceTemplate() || resource == null
                || !ProcessingConstants.UNIFIED_CONSOLE_TYPE.equals(resource.getType())
                || ProcessingConstants.REFERENCE_TYPE_ATTENDANCE_REGISTER.equals(resource.getReferenceType())) {
            return null;
        }
        String tenantId = resource.getTenantId();
        CampaignSearchResponse.CampaignDetail clone = campaignService.searchCampaignById(resource.getReferenceId(), tenantId, requestInfo);
        String sourceId = clone == null || clone.getAdditionalDetails() == null ? null : trimToNull(clone.getAdditionalDetails().getClonedCampaignId());
        if (sourceId == null || trimToNull(clone.getParentId()) != null) {
            return null;   // not a clone, or an edit of a created campaign
        }
        if (!isDeliveryConditionCampaignType(clone.getProjectType())) {
            return null;   // the clone rules follow the delivery conditions, which only these campaign types have (POLIO)
        }
        CampaignSearchResponse.CampaignDetail source = campaignService.searchCampaignById(sourceId, tenantId, requestInfo);
        if (source == null
                || !Objects.equals(trimToNull(clone.getHierarchyType()), trimToNull(source.getHierarchyType()))
                || !Objects.equals(OutsideHouseholdTypeMasterService.normalize(clone.getProjectType()),
                                   OutsideHouseholdTypeMasterService.normalize(source.getProjectType()))
                || !boundaryCodes(clone).equals(boundaryCodes(source))) {
            return null;   // a different area or type: the source's rows would not fit
        }
        String sourceFileStoreId = unifiedFile(source);
        if (sourceFileStoreId == null) {
            return null;
        }
        Object requested = resource.getAdditionalDetails() == null
                ? null : resource.getAdditionalDetails().get(ProcessingConstants.GENERATE_DETAIL_DELIVERY_METHODS_KEY);
        Set<String> cloneMethods = requested instanceof List
                ? OutsideHouseholdTypeMasterService.deliveryMethodCodes((List<?>) requested)
                : OutsideHouseholdTypeMasterService.extractDeliveryMethods(clone);
        boolean cloneUsesOutsideHousehold = cloneMethods.contains(ProcessingConstants.OUTSIDE_HOUSEHOLD_DELIVERY_METHOD);
        boolean sourceUsesOutsideHousehold = OutsideHouseholdTypeMasterService.extractDeliveryMethods(source)
                .contains(ProcessingConstants.OUTSIDE_HOUSEHOLD_DELIVERY_METHOD);
        return new CloneOfSource(sourceId, sourceFileStoreId, cloneUsesOutsideHousehold == sourceUsesOutsideHousehold);
    }

    /** One of excel.ingestion.outside.household.campaign.types (POLIO by default), the types with delivery conditions. */
    private boolean isDeliveryConditionCampaignType(String projectType) {
        String type = OutsideHouseholdTypeMasterService.normalize(projectType);
        List<String> types = config.getOutsideHouseholdCampaignTypes();
        return type != null && types != null
                && types.stream().map(OutsideHouseholdTypeMasterService::normalize).anyMatch(type::equals);
    }

    private static Set<String> boundaryCodes(CampaignSearchResponse.CampaignDetail campaign) {
        return campaign.getBoundaries() == null ? Set.of() : campaign.getBoundaries().stream()
                .map(b -> b == null ? null : trimToNull(b.getCode())).filter(Objects::nonNull).collect(Collectors.toSet());
    }

    private static String unifiedFile(CampaignSearchResponse.CampaignDetail source) {
        if (source.getResources() == null) {
            return null;
        }
        for (Map<String, Object> r : source.getResources()) {
            if (r != null && UNIFIED_CONSOLE_RESOURCE_TYPE.equals(r.get("type"))) {
                Object id = r.get("filestoreId") != null ? r.get("filestoreId") : r.get("fileStoreId");
                String fileStoreId = id instanceof String ? trimToNull((String) id) : null;
                if (fileStoreId != null) {
                    return fileStoreId;
                }
            }
        }
        return null;
    }

    private static String trimToNull(String value) {
        return value == null || value.trim().isEmpty() ? null : value.trim();
    }
}
