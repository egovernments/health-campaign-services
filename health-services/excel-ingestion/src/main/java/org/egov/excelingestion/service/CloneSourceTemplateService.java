package org.egov.excelingestion.service;

import lombok.extern.slf4j.Slf4j;
import org.apache.poi.ss.usermodel.Workbook;
import org.apache.poi.xssf.usermodel.XSSFWorkbook;
import org.egov.common.contract.request.RequestInfo;
import org.egov.excelingestion.config.ExcelIngestionConfig;
import org.egov.excelingestion.config.ProcessingConstants;
import org.egov.excelingestion.web.models.CampaignSearchResponse;
import org.egov.excelingestion.web.models.GenerateResource;
import org.springframework.stereotype.Service;

import java.io.ByteArrayInputStream;
import java.io.ByteArrayOutputStream;
import java.util.List;
import java.util.Map;
import java.util.Objects;
import java.util.Set;
import java.util.stream.Collectors;

/**
 * A clone's template keeps its source campaign's data. When the clone agrees with its source on Outside Household (both
 * use it, or neither does), its template is the source's filled file itself. When the clone adds or drops Outside
 * Household, its template is generated as for any campaign (so the Outside Household sheet appears with the area's sites,
 * or not at all) and the source's users, targets and facilities are copied into it. Only for a clone on its source's area.
 */
@Service
@Slf4j
public class CloneSourceTemplateService {

    static final String UNIFIED_CONSOLE_RESOURCE_TYPE = "unified-console-resources";

    private final CampaignService campaignService;
    private final FileStoreService fileStoreService;
    private final ExcelIngestionConfig config;

    public CloneSourceTemplateService(CampaignService campaignService, FileStoreService fileStoreService, ExcelIngestionConfig config) {
        this.campaignService = campaignService;
        this.fileStoreService = fileStoreService;
        this.config = config;
    }

    /** A clone on its source's area whose source has a filled file. */
    private record CloneOfSource(String sourceId, String sourceFileStoreId, boolean sameOutsideHouseholdChoice) {
    }

    /** The source's file id to use as this generation's template, or null to generate the template as usual. */
    public String sourceFileForUnchangedClone(GenerateResource resource, RequestInfo requestInfo) {
        try {
            CloneOfSource clone = cloneOfSource(resource, requestInfo);
            if (clone == null || !clone.sameOutsideHouseholdChoice()) {
                return null;
            }
            log.info("Clone {} agrees with its source {} on Outside Household: template = source file {}",
                    resource.getReferenceId(), clone.sourceId(), clone.sourceFileStoreId());
            return clone.sourceFileStoreId();
        } catch (Exception e) {
            log.warn("Could not compare clone {} with its source; generating the template as usual: {}",
                    resource.getReferenceId(), e.getMessage());
            return null;
        }
    }

    /**
     * For a clone that adds or drops Outside Household: the generated template with the source's rows copied into it.
     * Any other generation, or any failure, returns the generated bytes unchanged.
     */
    public byte[] withSourceData(GenerateResource resource, RequestInfo requestInfo, byte[] generated) {
        if (generated == null) {
            return null;
        }
        try {
            CloneOfSource clone = cloneOfSource(resource, requestInfo);
            if (clone == null || clone.sameOutsideHouseholdChoice()) {
                return generated;
            }
            try (Workbook source = fileStoreService.downloadExcelFromFileStore(clone.sourceFileStoreId(), resource.getTenantId());
                 XSSFWorkbook template = new XSSFWorkbook(new ByteArrayInputStream(generated))) {
                int rows = CloneSourceDataMerger.copyRows(source, template);
                ByteArrayOutputStream out = new ByteArrayOutputStream(generated.length + 64 * 1024);
                template.write(out);
                log.info("Clone {} changed Outside Household from its source {}: copied {} rows of source file {} into the new template",
                        resource.getReferenceId(), clone.sourceId(), rows, clone.sourceFileStoreId());
                return out.toByteArray();
            }
        } catch (Exception e) {
            log.warn("Could not copy the source's rows into clone {}'s template; keeping the generated template: {}",
                    resource.getReferenceId(), e.getMessage());
            return generated;
        }
    }

    private CloneOfSource cloneOfSource(GenerateResource resource, RequestInfo requestInfo) {
        if (!config.isCloneReuseSourceTemplate() || resource == null
                || !ProcessingConstants.UNIFIED_CONSOLE_TYPE.equals(resource.getType())
                || ProcessingConstants.REFERENCE_TYPE_ATTENDANCE_REGISTER.equals(resource.getReferenceType())) {
            return null;
        }
        String tenantId = resource.getTenantId();
        CampaignSearchResponse.CampaignDetail clone = campaignService.searchCampaignById(resource.getReferenceId(), tenantId, requestInfo);
        String sourceId = clone == null || clone.getAdditionalDetails() == null ? null : trimToNull(clone.getAdditionalDetails().getClonedCampaignId());
        if (sourceId == null || trimToNull(clone.getParentId()) != null) {
            return null;   // not a clone, or an edit of a created campaign
        }
        CampaignSearchResponse.CampaignDetail source = campaignService.searchCampaignById(sourceId, tenantId, requestInfo);
        if (source == null
                || !Objects.equals(trimToNull(clone.getHierarchyType()), trimToNull(source.getHierarchyType()))
                || !Objects.equals(OutsideHouseholdTypeMasterService.normalize(clone.getProjectType()),
                                   OutsideHouseholdTypeMasterService.normalize(source.getProjectType()))
                || !boundaryCodes(clone).equals(boundaryCodes(source))) {
            return null;   // a different area or type: the source's rows would not fit
        }
        String sourceFileStoreId = unifiedFile(source);
        if (sourceFileStoreId == null) {
            return null;
        }
        Object requested = resource.getAdditionalDetails() == null
                ? null : resource.getAdditionalDetails().get(ProcessingConstants.GENERATE_DETAIL_DELIVERY_METHODS_KEY);
        Set<String> cloneMethods = requested instanceof List
                ? OutsideHouseholdTypeMasterService.deliveryMethodCodes((List<?>) requested)
                : OutsideHouseholdTypeMasterService.extractDeliveryMethods(clone);
        boolean cloneUsesOutsideHousehold = cloneMethods.contains(ProcessingConstants.OUTSIDE_HOUSEHOLD_DELIVERY_METHOD);
        boolean sourceUsesOutsideHousehold = OutsideHouseholdTypeMasterService.extractDeliveryMethods(source)
                .contains(ProcessingConstants.OUTSIDE_HOUSEHOLD_DELIVERY_METHOD);
        return new CloneOfSource(sourceId, sourceFileStoreId, cloneUsesOutsideHousehold == sourceUsesOutsideHousehold);
    }

    private static Set<String> boundaryCodes(CampaignSearchResponse.CampaignDetail campaign) {
        return campaign.getBoundaries() == null ? Set.of() : campaign.getBoundaries().stream()
                .map(b -> b == null ? null : trimToNull(b.getCode())).filter(Objects::nonNull).collect(Collectors.toSet());
    }

    private static String unifiedFile(CampaignSearchResponse.CampaignDetail source) {
        if (source.getResources() == null) {
            return null;
        }
        for (Map<String, Object> r : source.getResources()) {
            if (r != null && UNIFIED_CONSOLE_RESOURCE_TYPE.equals(r.get("type"))) {
                Object id = r.get("filestoreId") != null ? r.get("filestoreId") : r.get("fileStoreId");
                String fileStoreId = id instanceof String ? trimToNull((String) id) : null;
                if (fileStoreId != null) {
                    return fileStoreId;
                }
            }
        }
        return null;
    }

    private static String trimToNull(String value) {
        return value == null || value.trim().isEmpty() ? null : value.trim();
    }
}
